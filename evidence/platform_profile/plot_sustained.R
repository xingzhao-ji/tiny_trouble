# Base R graphics. Reads derived CSVs; does not launch a game or alter raw samples.
args <- commandArgs(trailingOnly=TRUE)
stopifnot(length(args)==1)
p <- args[1]
b <- read.csv(file.path(p, 'plot_buckets.csv'))
r <- read.csv(file.path(p, 'plot_rss.csv'))
f <- read.csv(file.path(p, 'plot_focus.csv'))
png(file.path(p, 'frame_time_rss.png'), width=1500, height=1100, res=150, type='cairo')
par(mfrow=c(2,1), mar=c(4.5,4.5,3,1), oma=c(2.5,0,1,0), family='sans')
ymax <- max(50, b$max)
plot(b$seconds/60, b$p50, type='n', xlab='', ylab='Frame interval (ms)', ylim=c(8,ymax), log=if(ymax>100)'y' else '', main='Frozen Mac 0.2.3 · FAILED workload; 20-minute callback sample')
usr <- par('usr'); yr <- if(ymax>100) 10^usr[3:4] else usr[3:4]
for(i in seq_len(nrow(f))) if(f$focused[i]==0) rect(f$start[i]/60,yr[1],f$end[i]/60,yr[2],col='#fff0cf',border=NA)
abline(h=1000/60,col='#777777',lty=2)
lines(b$seconds/60,b$p50,col='#25747b',lwd=2)
lines(b$seconds/60,b$p95,col='#cf813b',lwd=1.5)
lines(b$seconds/60,b$p99,col='#a44a45',lwd=1.5)
points(b$seconds/60,b$max,pch=20,col='#505566',cex=.3)
legend('topright',legend=c('10 s p50','10 s p95','10 s p99','10 s maximum','Unfocused intervals'),col=c('#25747b','#cf813b','#a44a45','#505566','#fff0cf'),lty=c(1,1,1,NA,NA),pch=c(NA,NA,NA,20,15),bty='n',cex=.75)
plot(r$seconds/60,r$rss_mib,type='n',xlab='Measurement time (minutes; warmup excluded)',ylab='Game process RSS (MiB)',main='RSS includes collector/game allocations; no overhead subtraction')
u<-par('usr')
for(i in seq_len(nrow(f))) if(f$focused[i]==0) rect(f$start[i]/60,u[3],f$end[i]/60,u[4],col='#fff0cf',border=NA)
lines(r$seconds/60,r$rss_mib,col='#25747b',lwd=1.2)
mtext('M4 Pro · 1920×1080 · cap 60 / VSync · mixed focus · zero walking/flights/probes; not active-gameplay acceptance',outer=TRUE,side=1,line=.6,cex=.75)
dev.off()
