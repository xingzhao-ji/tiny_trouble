#!/usr/bin/env python3
"""Generate Godot constants from the shared Figma/runtime token contract."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "design/figma/tokens.json"
TARGET = ROOT / "scripts/platform/design_tokens.gd"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    raw = SOURCE.read_bytes()
    data = json.loads(raw)
    assert data["schema_version"] == 1
    lines = ["extends RefCounted", "## Generated by scripts/sync_design_tokens.py; edit design/figma/tokens.json.",
             f'const SOURCE_SHA256 = "{hashlib.sha256(raw).hexdigest()}"']
    for group, prefix in [("colors", "COLOR"), ("typography", "TYPE"), ("radii", "RADIUS"), ("layout", "LAYOUT")]:
        for name, value in data[group].items():
            assert name.replace("_", "").isalnum() and isinstance(value, (str, int, float))
            expression = f'Color({json.dumps(value)})' if group == "colors" else json.dumps(value)
            lines.append(f"const {prefix}_{name.upper()} = {expression}")
    expected = "\n".join(lines) + "\n"
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != expected:
            raise SystemExit("Design tokens are out of sync. Run scripts/sync_design_tokens.py.")
        print("PASS: shared design tokens match generated Godot constants.")
    else:
        TARGET.write_text(expected)
        print("Generated", TARGET.relative_to(ROOT))


if __name__ == "__main__":
    main()
